export function getProduct(slug: string): Product | undefined {
  return products.find((p) => p.slug === slug);
}

export function getFeaturedProducts(): Product[] {
  return products.filter((p) => p.featured).slice(0, 8);
}

export function getNewProducts(): Product[] {
  return products.filter((p) => p.isNew);
}

export function getProductsByCategory(categorySlug: string): Product[] {
  return products.filter((p) => p.categorySlug === categorySlug);
}

export function getRelatedProducts(slug: string, categorySlug: string, limit = 4): Product[] {
  return products.filter((p) => p.slug !== slug && p.categorySlug === categorySlug).slice(0, limit);
}

export function searchProducts(query: string): Product[] {
  const q = query.trim().toLowerCase();
  if (!q) return [];
  return products.filter((p) => {
    const hay = [p.name, p.brand, p.shortDescription, p.description, p.categoryName, ...(p.tags ?? [])]
      .join(" ")
      .toLowerCase();
    return hay.includes(q);
  });
}
